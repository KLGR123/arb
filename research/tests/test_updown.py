def test_missing_data_is_not_forward_filled_or_interpolated():
    path = PricePath(((0, 1), (1, 2), (10, 3), (11, 4)))
    with pytest.raises(ValueError):
        path.twap(11, 11)
    with pytest.raises(ValueError):
        path.index(12)
    with pytest.raises(ValueError):
        flat().sigma(10)
    with pytest.raises(ValueError):
        fair_up(flat(), 1000, 1300, 999)


def test_real_recorded_market_rules_are_required_and_truth_is_binary():
    event = read_recording(RECORDING)["markets"][0]["event"]
    assert parse_market(event)["end"] - parse_market(event)["start"] == 300
    for change in ("lookback", "source", "unresolved", "split", "fee"):
        invalid = copy.deepcopy(event)
        market = invalid["markets"][0]
        if change == "lookback":
            market["cryptoMarketConfig"]["twapLookbackSeconds"] = 30
        elif change == "source":
            market["resolutionSource"] = "https://example.org/spot"
        elif change == "unresolved":
            market["umaResolutionStatus"] = "proposed"
        elif change == "split":
            market["outcomePrices"] = '["0.5","0.5"]'
        else:
            market["feeSchedule"]["exponent"] = 2
        with pytest.raises(ValueError):
            parse_market(invalid)


def test_real_recording_replay_fees_and_latency_without_network(monkeypatch):
    def no_network(*args, **kwargs):
        raise AssertionError("CI cannot fetch public data")
    monkeypatch.setattr(httpx.Client, "get", no_network)
    recording = read_recording(RECORDING)
    # Two real markets suffice for this regression; the full 60-market evidence
    # is regenerated by the documented CLI (the threshold must remain unmet here).
    recording["markets"] = recording["markets"][:2]
    recording["selection"]["count"] = 2
    report = analyze(recording, delays=(0, .05, 2))
    assert report["status"] == "incomplete"
    assert report["execution"] == "disabled"
    assert report["settlement"]["markets"] == 2
    assert not report["errors"]
    assert len(report["latency"]) == 9
    assert report["samples"]
    for row in report["samples"]:
        assert 0 <= row["fair_up"] <= 1
        assert row["remaining_seconds"] >= 60
        p = Decimal(str(row["reference_price"]))
        expected_fee = (Decimal(".07") * p * (1-p)).quantize(Decimal(".00001"))
        assert row["fee_usd_per_share"] == float(expected_fee)
    zero = report["latency"][0]
    # Fractional order latency cannot be resolved with one-second input;
    # it produces an explicit flat sensitivity, not invented subsecond prices.
    assert zero["net_edge_usd_per_share"] == report["latency"][1]["net_edge_usd_per_share"]


def test_settlement_rows_never_become_predictors_and_empty_history_is_incomplete():
    recording = read_recording(RECORDING)
    recording["markets"] = recording["markets"][:1]
    recording["selection"]["count"] = 1
    before = analyze(recording, delays=(0,))
    recording["markets"][0]["history"].append({"timestamp": 0, "price": 1, "resolution_seconds": 0})
    assert analyze(recording, delays=(0,))["samples"] == before["samples"]
    recording["markets"][0]["history"] = []
    report = analyze(recording, delays=(0,))
    assert report["status"] == "incomplete" and report["errors"]


def test_declared_cohort_and_all_four_observations_are_required():
    recording = read_recording(RECORDING)
    truncated = copy.deepcopy(recording)
    truncated["markets"] = truncated["markets"][:50]
    report = analyze(truncated, delays=(0,))
    assert report["status"] == "incomplete" and report["errors"]
    for market in recording["markets"]:
        market["history"] = market["history"][:1]
    report = analyze(recording, delays=(0,))
    assert report["status"] == "incomplete" and report["baseline"]["samples"] == 0
    with pytest.raises(ValueError, match="zero baseline"):
        analyze(recording, delays=(.05,))


def test_full_recorded_cohort_matches_published_evidence():
    import hashlib
    import json
    recording = read_recording(RECORDING)
    report = analyze(recording, delays=(0,))
    published = json.loads((Path(__file__).parents[2] / "docs/reports/crypto-updown-pricing.json").read_text())
    assert report["status"] == "complete"
    assert report["settlement"]["matches"] == 59
    assert report["coverage"]["baseline_points"] == 240
    for key in ("settlement", "baseline", "buckets", "samples"):
        assert report[key] == published[key]
    assert hashlib.sha256(RECORDING.read_bytes()).hexdigest() == published["input_sha256"]


def test_scoped_proxy_and_get_allowlist_retry_and_sanitized_errors(monkeypatch):
    calls, constructor_args, sleeps = [], [], []
    monkeypatch.setenv("ARB_POLYMARKET_PROXY", "socks5h://user:private-secret@example.org:1234")
    def transport(request):
        calls.append(request)
        return httpx.Response(429, headers={"Retry-After": "2"}) if len(calls) == 1 else httpx.Response(200, json=[])
    real_client = httpx.Client
    def factory(**kwargs):
        constructor_args.append(kwargs)
        return real_client(transport=httpx.MockTransport(transport), trust_env=False)
    monkeypatch.setattr(httpx, "Client", factory)
    class Limiter:
        def acquire(self):
            pass
    with StudySources(sleep=sleeps.append, limiter=Limiter()) as source:
        assert source.get("gamma") == []
        assert len(sleeps) == 1 and sleeps[0] >= 2
        assert all(request.method == "GET" for request in calls)
        with pytest.raises(ValueError):
            source.get("orders")
        assert "proxy" in constructor_args[0] and "proxy" not in constructor_args[1]
        def failing(*args, **kwargs):
            raise httpx.ConnectError("private-secret")
        monkeypatch.setattr(source.poly.http, "get", failing)
        with pytest.raises(OSError, match="public_gamma_read_failed") as error:
            source.get("gamma")
        assert "private-secret" not in str(error.value)
