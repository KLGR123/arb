RECORDING = Path(__file__).parents[1] / "fixtures/updown/btc-5m-20261029.json.gz"


def flat(price="100"):
    return PricePath(tuple((i, price) for i in range(0, 1301)))


def test_exact_weighted_integral_tie_and_window_edges():
    path = PricePath(((0, "100"), (1, "103"), (3, "106"), (4, "106")))
    assert path.integral(.5, 3.5) == Decimal("309.0")
    assert path.twap(3, 3) == Decimal(102)
    constant = flat()
    assert fair_up(constant, 1000, 1300, 1300, sigma=.01) == 1
    assert fair_up(constant, 1000, 1300, 1000, sigma=0) == 1
    assert fair_up(constant, 1000, 1300, 1000, sigma=.01) == .5


def test_diffusion_before_and_inside_final_twap_window():
    # Strike=100, current price=101. Before the final window the variance
    # coefficient is (1240-1100)+60/3=160 seconds.
    points = [(i, "100" if i < 1100 else "101") for i in range(1301)]
    path = PricePath(tuple(points))
    expected = NormalDist().cdf(1 / (101 * .001 * math.sqrt(160)))
    assert fair_up(path, 1000, 1300, 1100, sigma=.001) == pytest.approx(expected)
    # At 1270, half of the final minute is known at 101. Remaining variance
    # is 30^3/(3*60^2), not 30 or 60 seconds.
    expected = NormalDist().cdf(1 / (101 * .001 * math.sqrt(2.5)))
    assert fair_up(path, 1000, 1300, 1270, sigma=.001) == pytest.approx(expected)


def test_probability_accounts_for_known_partial_average():
    points = [(i, "100" if i < 1240 else "102" if i < 1270 else "98") for i in range(1301)]
    # Known 30s * 102 + expected 30s * 98 averages exactly 100.
    assert fair_up(PricePath(tuple(points)), 1000, 1300, 1270, sigma=.001) == pytest.approx(.5)


def test_future_prices_cannot_change_signal_or_volatility():
    points = [(i, str(100 + (i % 7) / 100)) for i in range(1301)]
    original = PricePath(tuple(points))
    changed = PricePath(tuple((t, "100000" if t > 1200 else p) for t, p in points))
    assert original.sigma(1200) == changed.sigma(1200)
    assert fair_up(original, 1000, 1300, 1200) == fair_up(changed, 1000, 1300, 1200)
    assert original.sigma(1200) > 0


